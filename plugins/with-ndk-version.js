const { withProjectBuildGradle } = require("expo/config-plugins");

// Expo SDK 57's default NDK. Expo's root plugin puts this in
// rootProject.ext.ndkVersion, but only propagates the *cmake* version down to
// subprojects — each module has to read ndkVersion itself. expo-updates declares
// an externalNativeBuild without doing so, so it silently falls back to AGP's
// bundled default (27.0.12077973) and fails with CXX1101 unless that exact NDK
// happens to be installed. Force every Android subproject onto the one Expo wants.
const DEFAULT_NDK_VERSION = "27.1.12297006";

const ANCHOR = "// @generated by with-ndk-version";

const withNdkVersion = (config, { ndkVersion = DEFAULT_NDK_VERSION } = {}) =>
  withProjectBuildGradle(config, (config) => {
    if (config.modResults.language !== "groovy") {
      throw new Error(
        "with-ndk-version only supports Groovy build.gradle, found " +
          config.modResults.language
      );
    }

    if (config.modResults.contents.includes(ANCHOR)) {
      return config;
    }

    config.modResults.contents += `
${ANCHOR}
allprojects { subproject ->
  subproject.plugins.withId("com.android.library") {
    subproject.android.ndkVersion = "${ndkVersion}"
  }
  subproject.plugins.withId("com.android.application") {
    subproject.android.ndkVersion = "${ndkVersion}"
  }
}
`;

    return config;
  });

module.exports = withNdkVersion;
